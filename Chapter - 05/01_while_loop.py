count = 1  # Counter variable
# Iteration -> process of repeating steps multiple times

while count <= 5 : # Loop stops when condition becomes false
    print("hello")
    count +=1       # incrementing counter variable

# Incrementing is done inside the loop
print (count,"\n")

# Alternatively,
i = 1 # Generally iterators are small lik x,y,z,i,etc etc.
while i <= 5:
    print("Hello")
    i+=1
print("")

